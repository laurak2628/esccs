const express = require("express");

const app = express();

const PORT = process.env.PORT || 3000;

app.get("/", (req, res) => {
    res.send(`
        <!DOCTYPE html>
        <html>
        <head>
            <title>Event Safety & Crowd Coordination System (ESCCS) </title>
        </head>
        <body>
            <h1>Event Safety & Crowd Coordination System (ESCCS)</h1>
        </body>
        </html>
    `);
});

app.listen(PORT, "0.0.0.0", () => {
    console.log(`Server listening on port ${PORT}`);
});